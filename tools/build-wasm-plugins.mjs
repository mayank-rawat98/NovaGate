import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

/**
 * Builds the WebAssembly catalog plugins and sandbox test fixtures from C
 * (clang with the wasm32 target and wasm-ld), and regenerates the admin
 * API's embedded catalog. The built modules are committed, so tests and CI
 * do not need clang; rerun this after changing a source file.
 */
const root = resolve('libs/plugin-sdk/wasm');
const clang = process.env.CLANG ?? 'clang';
const common = [
  '--target=wasm32',
  '-O2',
  '-nostdlib',
  '-fno-builtin',
  '-Wl,--no-entry',
  '-Wl,--strip-all',
];

function build(source, { importMemory = true } = {}) {
  const output = source.replace(/\.c$/, '.wasm');
  execFileSync(clang, [
    ...common,
    ...(importMemory
      ? ['-Wl,--import-memory', '-Wl,--initial-memory=131072']
      : []),
    '-o',
    output,
    source,
  ]);
  return output;
}

for (const directory of ['catalog', 'fixtures'])
  for (const file of readdirSync(join(root, directory)).sort())
    if (file.endsWith('.c'))
      build(join(root, directory, file), {
        importMemory: file !== 'own-memory.c',
      });

const catalog = JSON.parse(
  readFileSync(join(root, 'catalog/catalog.json'), 'utf8'),
);
const entries = catalog.map((entry) => {
  const bytes = readFileSync(join(root, 'catalog', `${entry.id}.wasm`));
  return {
    ...entry,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    size: bytes.length,
    module: bytes.toString('base64'),
  };
});
writeFileSync(
  'apps/admin-api/src/wasm-plugins/catalog.generated.ts',
  `// Generated by tools/build-wasm-plugins.mjs from ${basename(root)}/catalog; do not edit.\n` +
    `import type { WasmCatalogEntry } from '@api-gateway/shared-types';\n\n` +
    `export const WASM_CATALOG: Array<Omit<WasmCatalogEntry, 'hooks'> & { module: string }> = ${JSON.stringify(entries, null, 2)};\n`,
);
console.log(
  `Built ${entries.length} catalog plugins and the sandbox fixtures in ${root}.`,
);
